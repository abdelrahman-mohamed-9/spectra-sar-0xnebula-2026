"""PostgreSQL connection and a minimal safe repository for SPECTRA-SAR.

Requires psycopg 3. Never store rasters in PostgreSQL; store hashes and URIs.
"""
import os
from contextlib import contextmanager
from uuid import UUID


def _driver():
    try:
        import psycopg
    except ImportError as exc:
        raise RuntimeError('Install dependencies: pip install -r requirements.txt') from exc
    return psycopg


def connection_kwargs(environ=None):
    e = os.environ if environ is None else environ
    password = e.get('POSTGRES_PASSWORD', '')
    if not password or 'CHANGE_ME' in password:
        raise ValueError('Set a non-placeholder POSTGRES_PASSWORD')
    return {
        'host': e.get('DB_HOST', e.get('DATABASE_HOST', 'localhost')),
        'port': int(e.get('POSTGRES_PORT', e.get('DATABASE_PORT', '5432'))),
        'dbname': e.get('POSTGRES_DB', 'spectra_sar'),
        'user': e.get('POSTGRES_USER', 'spectra'),
        'password': password,
        'connect_timeout': 5,
    }


@contextmanager
def db_connection(environ=None):
    """Transaction commits on success, rolls back on exception."""
    with _driver().connect(**connection_kwargs(environ)) as conn:
        yield conn


def create_run(conn, run_id: UUID, config=None):
    """Idempotently create a QUEUED run. UUID is generated by caller."""
    from psycopg.types.json import Jsonb
    with conn.cursor() as cur:
        cur.execute(
            "INSERT INTO processing_runs(id,config) VALUES (%s,%s) "
            "ON CONFLICT (id) DO NOTHING RETURNING id",
            (run_id, Jsonb(config or {})),
        )
        return cur.fetchone() is not None


def get_run(conn, run_id: UUID):
    with conn.cursor() as cur:
        cur.execute(
            "SELECT id,status,created_at,started_at,finished_at,error_code "
            "FROM processing_runs WHERE id=%s", (run_id,)
        )
        row = cur.fetchone()
        if row is None:
            return None
        return dict(zip(('id','status','created_at','started_at','finished_at','error_code'), row))


def set_run_status(conn, run_id: UUID, new_status: str, *, error_code=None):
    """Restrict changes to known legal transitions; concurrency-safe row lock."""
    allowed = {
        'QUEUED': {'RUNNING', 'REJECTED', 'FAILED'},
        'RUNNING': {'SUCCEEDED', 'FAILED', 'REJECTED'},
        'SUCCEEDED': set(), 'FAILED': set(), 'REJECTED': set(),
    }
    with conn.cursor() as cur:
        cur.execute('SELECT status FROM processing_runs WHERE id=%s FOR UPDATE', (run_id,))
        row = cur.fetchone()
        if row is None:
            raise KeyError(f'Unknown run: {run_id}')
        if new_status not in allowed[row[0]]:
            raise ValueError(f'Invalid run transition {row[0]} -> {new_status}')
        cur.execute(
            "UPDATE processing_runs SET status=%s, "
            "started_at=CASE WHEN %s='RUNNING' THEN now() ELSE started_at END, "
            "finished_at=CASE WHEN %s IN ('SUCCEEDED','FAILED','REJECTED') THEN now() ELSE finished_at END, "
            "error_code=%s WHERE id=%s",
            (new_status, new_status, new_status, error_code, run_id),
        )
