def _write_json(path, obj):
    Path(path).write_text(json.dumps(obj, indent=2, ensure_ascii=False, allow_nan=False) + '\n', encoding='utf-8')


def _link_or_copy(src, dst):
    src, dst = Path(src).resolve(), Path(dst)
    if dst.exists(): raise ValueError(f'Staging file already exists: {dst}')
    try: os.link(src, dst)
    except OSError: shutil.copy2(src, dst)


def prepare_filtered_pair(source_dir, filter_dir, stage_dir, polarization):
    """Stage filtered rasters + original masks with coherent *real* provenance.

    Hardlinks preferred to minimize disk; copy is fallback. Never symlink outside root.
    """
    source_dir, filter_dir, stage_dir = map(lambda x: Path(x).resolve(), (source_dir, filter_dir, stage_dir))
    if stage_dir.exists(): raise ValueError('Stage already exists; select a new output directory')
    stage_dir.mkdir(parents=True)
    manifest = json.loads(json.dumps(load_manifest(source_dir)))
    if polarization not in manifest['polarizations']: raise ValueError('Missing polarization')
    # Do not suggest filtered data exists for unprocessed polarization.
    manifest['polarizations'] = [polarization]
    for side in ('before', 'after'):
        rec = manifest[side]
        filtered = filter_dir / f'{side}_{polarization}_lee.tif'
        if not filtered.is_file(): raise FileNotFoundError(filtered)
        new_raster = f'{side}_{polarization}_filtered.tif'
        _link_or_copy(filtered, stage_dir / new_raster)
        rec['raster_files'] = {polarization: new_raster}
        for field in ('valid_mask_file', 'layover_shadow_mask_file'):
            if rec.get(field):
                raw = safe_pair_file(source_dir, rec[field])
                name = f'{side}_{field}.tif'
                _link_or_copy(raw, stage_dir / name)
                rec[field] = name
    manifest['processing_software'] = str(manifest['processing_software']) + ' + SPECTRA-SAR M2 Lee filtering'
    manifest['processing_version'] = str(manifest['processing_version']) + ' + T03-v1'
    _write_json(stage_dir / 'manifest.json', manifest)
    qa = inspect_pair(stage_dir)
    if qa['status'] == 'REJECT': raise ValueError('Filtered pair fails T02: '+str(qa['errors']))
    return qa


def _grid_and_digest(path, reference=None):
    path = Path(path)
    if not path.is_file(): raise FileNotFoundError(path)
    digest = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(1024*1024), b''): digest.update(chunk)
    with rasterio.open(path) as r:
        info = {'sha256':digest.hexdigest(), 'bands':r.count, 'dtype':r.dtypes[0],
                'width':r.width,'height':r.height,'crs':str(r.crs),
                'transform':list(r.transform)[:6], 'nodata':r.nodata}
        grid = (r.crs, r.transform, r.width, r.height)
        if reference is not None and grid != reference: raise ValueError(f'Output grid mismatch: {path.name}')
        return info,grid


def publish_m3(output_dir, *, pair_id, polarization, qa, registration, filtered_qa, change, classification=None, uncertainty=None, evaluation=None):
    out = Path(output_dir).resolve()
    changes = out / 'T05_change'
    # Use T05's own declared filenames, rather than assuming arbitrary names.
    files = change['files']
    artifacts = {}
    ref = None
    for role, file in files.items():
        p = Path(file)
        # T05 filenames are generated by local code, but prevent unintended traversal.
        if p.is_absolute():
            if p.resolve().parent != changes: raise ValueError('T05 path escapes output')
        else:
            p = changes / p
        if p.suffix.lower() != '.tif': continue
        details, grid = _grid_and_digest(p, ref)
        if ref is None: ref = grid
        artifacts[role] = {'path':p.relative_to(out).as_posix(), **details}
    if not artifacts: raise ValueError('No T05 geospatial output artifacts')
    if classification is not None:
        for role in ('class_map','class_probabilities','uncalibrated_max_probability'):
            p = out/'T06_classification'/f'{role}.tif'
            details,_ = _grid_and_digest(p,ref)
            artifacts[role] = {'path':p.relative_to(out).as_posix(),**details}
    if uncertainty is not None:
        for role in ('normalized_entropy','top_two_margin','uncalibrated_max_probability','review_required'):
            p = out/'T07_uncertainty'/f'{role}.tif'
            details,_ = _grid_and_digest(p,ref)
            artifacts['uncertainty_'+role] = {'path':p.relative_to(out).as_posix(),**details}
    package = {
        'schema_version':'1.0', 'producer':'SPECTRA-SAR-M2-T09',
        'pair_id':pair_id, 'polarization':polarization,
        'created_utc':datetime.now(timezone.utc).isoformat(),
        'delivery_status':'EXPLORATORY_NOT_SCIENTIFICALLY_VALIDATED',
        'scientific_approval':False,
        'input_qa_status':qa['status'], 'filtered_input_qa_status':filtered_qa['status'],
        'registration_status':registration['status'],
        'registration_subpixel_certified':False,
        'change_detection':{'method':change['method'],'threshold_db':change['threshold_db'],
                            'candidate_change_area_km2':change['candidate_change_area_km2'],
                            'estimated_area_not_ground_truth':True},
        'classification_available':classification is not None,
        'uncertainty_available':uncertainty is not None,
        'evaluation_available':evaluation is not None,
        'artifacts':artifacts,
        'stage_reports':{'t02':'T02-qa.json','t04':'T04-registration.json',
                         't03':'T03_filtered/filter-report.json','t05':'T05_change/change-summary.json',
                         't06':'T06_classification/classification-summary.json' if classification is not None else None,
                         't07':'T07_uncertainty/uncertainty-summary.json' if uncertainty is not None else None,
                         't08':'T08_evaluation/evaluation-report.json' if evaluation is not None else None},
        'limitations':['No verified subpixel registration (<0.5 pixel) is available in T04.',
                       'Candidate changes are backscatter changes; event cause is not established.',
                       'AI outputs require a separately trained, trustworthy model and independent labels.',
                       'Model probabilities are not calibrated confidence.',
                       'M3 must not display these outputs as scientifically certified impact estimates.']
    }
    from jsonschema import validate
    schema = json.loads((Path(__file__).parent/'output_schema.json').read_text(encoding='utf-8'))
    validate(package, schema)
    _write_json(out/'m3-delivery.json',package)
    return package


def binary_candidate_mask(source, destination):
    """T05 0/1/2/255 -> T08 binary 0/1/255, preserving georeferencing."""
    source, destination = Path(source), Path(destination)
    with rasterio.open(source) as src:
        if src.count != 1: raise ValueError('T05 change mask requires one band')
        profile = src.profile.copy()
        with rasterio.open(destination, 'w', **profile) as dst:
            for _, win in src.block_windows(1):
                x = src.read(1, window=win)
                if not np.isin(x,[0,1,2,255]).all(): raise ValueError('Unknown T05 change class')
                dst.write(np.where(x==255,255,(x!=0).astype('uint8')).astype('uint8'),1,window=win)
            dst.update_tags(classes='0:no_candidate;1:any_candidate_change;255:invalid',
                            interpretation='candidate_change_only_not_event_ground_truth')


def run_pipeline(pair_dir, output_dir, *, polarization='VV', model_dir=None, threshold_db=3.,
                 tile_size=512, window=7, looks=4., allow_warning=False,
                 reference=None, provenance=None):
    src, out = Path(pair_dir).resolve(), Path(output_dir).resolve()
    if out == src or out in src.parents or src in out.parents:
        raise ValueError('Output and input directory trees must not overlap')
    if out.exists(): raise ValueError('Output directory exists: choose a new clean directory')
    if reference is not None and not Path(reference).is_file(): raise FileNotFoundError(reference)
    if provenance is not None and not Path(provenance).is_file(): raise FileNotFoundError(provenance)
    qa = inspect_pair(src)
    if qa['status']=='REJECT' or (qa['status']=='WARNING' and not allow_warning):
        raise ValueError('T02 blocked processing: '+json.dumps(qa))
    manifest = load_manifest(src)
    if polarization not in manifest['polarizations']: raise ValueError('Polarization missing')
    out.mkdir(parents=True)
    _write_json(out/'T02-qa.json',qa)
    # Evaluate residual shifts on *unfiltered* imagery; diagnostic only.
    registration = inspect_registration(src,polarization=polarization,allow_warning=allow_warning,
                                        patch=256)
    _write_json(out/'T04-registration.json',registration)
    if registration['status']=='REJECT': raise ValueError('T04 registration rejected inputs')
    process_pair(src,out/'T03_filtered',polarization=polarization,window=window,
                 looks=looks,tile=tile_size,allow_warning=allow_warning)
    staged = out/'staged_filtered_pair'
    filtered_qa = prepare_filtered_pair(src,out/'T03_filtered',staged,polarization)
    _write_json(out/'T02-filtered-qa.json',filtered_qa)
    # Existing T05/T06 explicitly allow only exploratory unverified registration.
    change = run_detection(staged,out/'T05_change',polarization=polarization,
                           threshold_db=threshold_db,tile_size=tile_size,
                           allow_unverified_registration=True)
    classification = uncertainty = evaluation = None
    if model_dir is not None:
        from ai_classifier import infer
        from uncertainty import run as run_uncertainty
        classification = infer(staged,model_dir,out/'T06_classification',polarization=polarization,
                               tile_size=tile_size,allow_unverified_registration=True)
        uncertainty = run_uncertainty(staged,out/'T06_classification',out/'T07_uncertainty',
                                     polarization=polarization,tile_size=max(16,tile_size),
                                     allow_unverified_registration=True)
    if reference is not None:
        from evaluation import evaluate
        # External ground truth still requires documented independence.
        (out/'T08_evaluation').mkdir(exist_ok=True)
        binary_prediction = out/'T08_evaluation'/f'binary_candidate_mask_{polarization}.tif'
        binary_candidate_mask(out/'T05_change'/f'change_mask_{polarization}.tif',binary_prediction)
        evaluation = evaluate(reference,binary_prediction,
                              out/'T05_change'/f'valid_mask_{polarization}.tif',
                              out/'T08_evaluation'/'evaluation-report.json',
                              mode='binary',provenance_path=provenance,allow_exploratory=True)
    return publish_m3(out,pair_id=manifest['pair_id'],polarization=polarization,
                      qa=qa,registration=registration,filtered_qa=filtered_qa,change=change,
                      classification=classification,uncertainty=uncertainty,evaluation=evaluation)


def main():
    p=argparse.ArgumentParser(description='SPECTRA-SAR M2 Phase-1 integration; exploratory outputs only')
    p.add_argument('pair_dir');p.add_argument('--out',required=True)
    p.add_argument('--polarization',choices=['VV','VH','HHHH'],default='VV')
    p.add_argument('--model-dir',help='Optional REAL trusted T06 trained model directory')
    p.add_argument('--reference',help='Optional real independent binary ground-truth GeoTIFF')
    p.add_argument('--provenance',help='Optional T08 provenance JSON')
    p.add_argument('--threshold-db',type=float,default=3.)
    p.add_argument('--tile-size',type=int,default=512)
    p.add_argument('--window',type=int,default=7)
    p.add_argument('--looks',type=float,default=4.)
    p.add_argument('--allow-warning',action='store_true')
    args=p.parse_args()
    try:
        report=run_pipeline(args.pair_dir,args.out,polarization=args.polarization,
                model_dir=args.model_dir,reference=args.reference,provenance=args.provenance,
                threshold_db=args.threshold_db,tile_size=args.tile_size,
                window=args.window,looks=args.looks,allow_warning=args.allow_warning)
    except Exception as exc:
        print(f'T09 pipeline FAILED: {exc}',file=sys.stderr)
        return 3
    print(json.dumps({'status':report['delivery_status'],'output':str(Path(args.out).resolve()/'m3-delivery.json')}))
    return 2 # exploratory, not scientific certification

if __name__=='__main__': raise SystemExit(main())
